#!/usr/bin/env python3
"""One-shot converter: cover.jpg -> a baked-in RGB565 C array.

Not part of the build. Run by hand when the ~10-album set changes, and the
output is committed like any other generated-once asset (icons.cpp is the
same idea, at 1 bit per pixel instead of 16).
"""
import sys
from pathlib import Path
from PIL import Image

SIZE = 96  # 96x96 RGB565 = 18,432 bytes per cover; 7 covers is ~130KB of flash.

ALBUMS = [
    # (source jpg, album tag exactly as MediaStore/ffprobe reports it, C identifier)
    ("from_mars_to_sirius.jpg", "From Mars To Sirius", "kFromMarsToSirius"),
    ("terra_incognita.jpg", "Terra Incognita", "kTerraIncognita"),
    ("the_link.jpg", "The link", "kTheLink"),
    ("lenfant_sauvage.jpg", "L'Enfant Sauvage", "kLEnfantSauvage"),
    ("the_way_of_all_flesh.jpg", "The Way Of All Flesh (vinyl)", "kTheWayOfAllFlesh"),
    ("fortitude.jpg", "Fortitude", "kFortitude"),
    ("magma.jpg", "Magma", "kMagma"),
]


def to_rgb565(im: Image.Image):
    im = im.convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
    out = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = im.getpixel((x, y))
            out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def emit_array(f, ident, pixels):
    f.write(f"const uint16_t {ident}[] = {{\n")
    for i in range(0, len(pixels), 12):
        row = pixels[i:i + 12]
        f.write("    " + ", ".join(f"0x{p:04x}" for p in row) + ",\n")
    f.write("};\n\n")


def main():
    src_dir = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    with open(out_path, "w") as f:
        f.write("// Generated by tools/make_album_art.py. Do not hand-edit.\n")
        f.write("//\n")
        f.write("// RGB565, row-major, straight blit -- Canvas::draw_image's format.\n")
        f.write('#include "ui/album_art.hpp"\n\n')
        f.write("namespace ui::album_art {\nnamespace {\n\n")
        for src, album, ident in ALBUMS:
            im = Image.open(src_dir / src)
            pixels = to_rgb565(im)
            emit_array(f, ident, pixels)
        f.write("}  // namespace\n\n")
        f.write(f"const Cover kGojira[] = {{\n")
        for _, album, ident in ALBUMS:
            esc = album.replace('"', '\\"')
            f.write(f'    {{"{esc}", {ident}, {SIZE}, {SIZE}}},\n')
        f.write("};\n")
        f.write(f"const size_t kGojiraCount = {len(ALBUMS)};\n\n")
        f.write("}  // namespace ui::album_art\n")
    print(f"wrote {out_path}, {len(ALBUMS)} covers, "
          f"{len(ALBUMS) * SIZE * SIZE * 2} bytes of pixel data")


if __name__ == "__main__":
    main()
